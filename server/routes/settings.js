import express from 'express';
import { z } from 'zod';
import { db, json, parseJson, getPlan, getUsage, allSettings, logAudit } from '../db.js';
import { requireAuth, userPublic } from '../auth.js';
import { providerStatus } from '../config.js';
import { asyncHandler } from '../errors.js';
import { parseBody } from '../validation.js';
import { sendNotification } from '../notifications.js';

const preferencesSchema = z.object({
  preferences: z.object({
    defaultNiche: z.string().max(120).optional(),
    defaultStyle: z.string().max(80).optional(),
    defaultLanguage: z.string().max(10).optional(),
    defaultVoice: z.string().max(80).optional(),
    timezone: z.string().max(80).optional(),
    defaultReviewRequired: z.boolean().optional(),
    emailNotifications: z.boolean().optional(),
  }),
});

export function settingsRouter() {
  const router = express.Router();
  router.use(requireAuth);

  router.get('/', asyncHandler(async (req, res) => {
    const [plan, usage, settings] = await Promise.all([getPlan(req.user.plan_id), getUsage(req.user.id), allSettings()]);
    res.json({
      user: userPublic(req.user),
      preferences: parseJson(req.user.metadata, {}),
      plan,
      usage,
      providerStatus: providerStatus(),
      settings: {
        contentPolicy: settings.content_policy,
        defaultReviewRequired: settings.default_review_required,
        autopilotEnabled: settings.autopilot_enabled,
        defaultPrivacy: settings.default_privacy,
        supportedLanguages: settings.supported_languages,
        supportedPlatforms: settings.supported_platforms,
        metricsSyncIntervalHours: settings.metrics_sync_interval_hours,
        maxPublishRetries: settings.max_publish_retries,
        captionReferenceCodes: settings.caption_reference_codes,
      },
    });
  }));

  router.patch('/', asyncHandler(async (req, res) => {
    const data = parseBody(preferencesSchema, req.body);
    const preferences = { ...parseJson(req.user.metadata, {}), ...data.preferences };
    await db('users').where({ id: req.user.id }).update({ metadata: json(preferences) });
    await logAudit({ userId: req.user.id, action: 'settings.update', entityType: 'user', entityId: req.user.id, details: data.preferences });
    res.json({ ok: true, preferences });
  }));

  router.post('/test-notification', asyncHandler(async (req, res) => {
    await sendNotification(req.user.id, {
      type: 'info',
      title: 'Notifications are working',
      body: 'This in-app notification was generated by the platform. Email or webhook delivery is active only when configured on the server.',
      actionUrl: '/app/settings',
    });
    res.json({ ok: true });
  }));

  router.get('/usage', asyncHandler(async (req, res) => {
    const [plan, usage] = await Promise.all([getPlan(req.user.plan_id), getUsage(req.user.id)]);
    res.json({ plan, usage });
  }));

  router.get('/plans', asyncHandler(async (_req, res) => {
    const rows = await db('plans').where({ active: true }).orderBy('sort_order', 'asc');
    res.json({ plans: rows.map((row) => ({ ...row, active: Boolean(row.active), features: parseJson(row.features, []) })) });
  }));

  router.get('/providers', asyncHandler(async (_req, res) => res.json(providerStatus())));

  return router;
}
